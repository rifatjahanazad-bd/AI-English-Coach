"""meme_validator.py - Validates generated memes before presenting to user.

Filters out defective placeholders, missing-background images,
and striped gray error images generated when meme templates fail.
"""

from pathlib import Path
from typing import Tuple, Union, Optional
import io
import numpy as np
from PIL import Image


def validate_meme_image(
    image_input: Union[str, Path, bytes, Image.Image]
) -> Tuple[bool, str]:
    """
    Validates whether a meme image is a genuine meme with valid graphic background,
    or a broken/striped placeholder generated by an invalid template.

    Returns:
        (is_valid: bool, reason: str)
    """
    try:
        if isinstance(image_input, (str, Path)):
            img = Image.open(Path(image_input))
        elif isinstance(image_input, bytes):
            img = Image.open(io.BytesIO(image_input))
        elif isinstance(image_input, Image.Image):
            img = image_input
        else:
            return False, "unsupported_image_type"

        # Check minimal dimensions
        w, h = img.size
        if w < 150 or h < 150:
            return False, "image_too_small"

        # Convert to RGB and HSV
        rgb_img = img.convert("RGB")
        hsv_img = img.convert("HSV")

        rgb_arr = np.array(rgb_img)
        hsv_arr = np.array(hsv_img)

        # Inspect central region (where background image is prominent, away from header/footer text)
        y_start, y_end = int(h * 0.20), int(h * 0.80)
        x_start, x_end = int(w * 0.20), int(w * 0.80)

        center_rgb = rgb_arr[y_start:y_end, x_start:x_end]
        center_sat = hsv_arr[y_start:y_end, x_start:x_end, 1]

        # Check 1: Saturation check
        # Placeholder memes with gray diagonal stripes have saturation close to 0 across the whole center
        mean_sat = float(np.mean(center_sat))
        max_sat = float(np.max(center_sat))

        # Check 2: Color channel variance in center (R vs G vs B difference)
        diff_rg = np.abs(center_rgb[:, :, 0].astype(int) - center_rgb[:, :, 1].astype(int))
        diff_gb = np.abs(center_rgb[:, :, 1].astype(int) - center_rgb[:, :, 2].astype(int))
        max_channel_diff = np.maximum(diff_rg, diff_gb)
        mean_channel_diff = float(np.mean(max_channel_diff))

        # Broken placeholder characteristics:
        # In placeholder stripes, mean_sat is nearly 0 (< 5.0) and mean_channel_diff is near 0 (< 3.0)
        # Genuine memes have rich colors with mean_sat > 15 and mean_channel_diff > 10.
        if mean_sat < 8.0 or mean_channel_diff < 4.0:
            return False, f"placeholder_striped_background (mean_sat={mean_sat:.3f}, diff={mean_channel_diff:.3f})"

        # Check 3: Check for blank / solid color images (zero variance)
        std_val = float(np.std(rgb_arr))
        if std_val < 5.0:
            return False, f"image_blank_or_solid (std={std_val:.2f})"

        # Check 4: Filter out text-only cards with no photographic background image
        # Genuine photographic meme templates have 20,000+ to 150,000+ unique colors.
        # Flat text cards with no background image have fewer than 5,000 unique colors.
        unique_colors = len(np.unique(rgb_arr.reshape(-1, 3), axis=0))
        if unique_colors < 10000:
            return False, f"no_background_image_text_card (unique_colors={unique_colors})"

        return True, "valid"

    except Exception as e:
        return False, f"validation_error: {str(e)}"


def is_valid_meme_image(image_input: Union[str, Path, bytes, Image.Image]) -> bool:
    """Convenience boolean check for meme image validity."""
    valid, _ = validate_meme_image(image_input)
    return valid
